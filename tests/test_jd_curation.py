def test_curation_typed_round_trip_is_atomic_and_context_validated(tmp_path, monkeypatch) -> None:
    source = source_data()
    sources = JDSourceCollection.from_dict(source_collection_data([source]))
    artifact = CurationArtifact.from_dict(curation_data([source]))
    catalog = production_role_catalog()
    path = save_curation_artifact(
        artifact, tmp_path / "curation.json", sources=sources, catalog=catalog
    )
    copy_path = save_curation_artifact(
        artifact, tmp_path / "copy.json", sources=sources, catalog=catalog
    )
    assert load_curation_artifact(path, sources=sources, catalog=catalog) == artifact
    assert path.read_bytes() == copy_path.read_bytes()

    original = path.read_bytes()
    monkeypatch.setattr("aarvia.phase2_storage.os.replace", lambda *_: (_ for _ in ()).throw(OSError("replace failed")))
    with pytest.raises(OSError, match="replace failed"):
        save_curation_artifact(artifact, path, sources=sources, catalog=catalog)
    assert path.read_bytes() == original


def test_unapproved_candidate_is_valid_curation_data_but_not_approved() -> None:
    source = source_data()
    candidate = extracted_candidate(source)
    data = curation_data([source])
    data["candidates"] = [candidate.to_dict()]
    data["clusters"] = []
    artifact = CurationArtifact.from_dict(data)
    sources = JDSourceCollection.from_dict(source_collection_data([source]))

    artifact.validate(sources, production_role_catalog())
    assert artifact.candidates[0].status.value == "candidate_extracted"
